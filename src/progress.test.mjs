import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {STORAGE_KEY,loadProgress,saveProgress,matchingQuestions,createReviewSession} from '../dist/progress.js';
const questions=JSON.parse(readFileSync(new URL('../dist/data.json',import.meta.url),'utf8')).questions;
const ids=new Set(questions.map(q=>q.id));
const ratings=new Map([['q001','known'],['q118','uncertain'],['q119','unknown']]);
assert.deepEqual(matchingQuestions(questions,ratings,['uncertain','unknown']).map(q=>q.id),['q118','q119']);
assert.deepEqual(matchingQuestions(questions,ratings,['uncertain','unknown'],1).map(q=>q.id),['q118']);
assert.equal(matchingQuestions(questions,ratings,['unrated']).length,132);
assert.equal(matchingQuestions(questions,ratings,[]).length,0);
assert.throws(()=>matchingQuestions(questions,ratings,['invalid']));
assert.throws(()=>matchingQuestions(questions,ratings,['known'],13));
assert.throws(()=>createReviewSession(questions,ratings,['known'],12));
const review=createReviewSession(questions,ratings,['uncertain','unknown']);
ratings.set('q118','known');
assert.deepEqual(review.questionIds,['q118','q119']);
assert.deepEqual(createReviewSession(questions,ratings,['uncertain','unknown']).questionIds,['q119']);
let saved=null;
const storage={getItem:key=>{assert.equal(key,STORAGE_KEY);return saved;},setItem:(key,value)=>{assert.equal(key,STORAGE_KEY);saved=value;}};
assert.equal(Object.keys(loadProgress(storage,ids).assessments).length,0);
saveProgress(storage,ids,'q001','drafts','현실적 불안\n신경증적 불안\n도덕적 불안');
saveProgress(storage,ids,'q001','assessments','known');
saveProgress(storage,ids,'q119','assessments','uncertain');
let restored=loadProgress(storage,ids);
assert.equal(restored.drafts.q001,'현실적 불안\n신경증적 불안\n도덕적 불안');
assert.deepEqual(restored.assessments,{q001:'known',q119:'uncertain'});
saveProgress(storage,ids,'q001','drafts','');
assert.equal(loadProgress(storage,ids).drafts.q001,'');
assert.equal(loadProgress(storage,ids).assessments.q119,'uncertain');
assert.throws(()=>saveProgress(storage,ids,'missing','assessments','known'));
assert.throws(()=>saveProgress(storage,ids,'q001','assessments','invalid'));
assert.throws(()=>saveProgress(storage,ids,'q001','drafts','x'.repeat(50001)));
saved=JSON.stringify({version:1,drafts:{q001:'kept',missing:'ignored',q119:12},assessments:{q001:'again',missing:'known',q119:'invalid'}});
assert.deepEqual(loadProgress(storage,ids),{version:1,drafts:{q001:'kept'},assessments:{q001:'unknown'}});
saved='{invalid';const corrupt=saved;
assert.throws(()=>saveProgress(storage,ids,'q001','assessments','known'));
assert.equal(saved,corrupt,'Unreadable records must not be overwritten.');
assert.throws(()=>loadProgress({getItem(){throw new Error('blocked');}},ids));
saved=null;
assert.throws(()=>saveProgress({...storage,setItem(){throw new Error('quota exceeded');}},ids,'q001','assessments','known'));
console.log('PASS: scoped multi-status reviews, fixed review queues, reload persistence, multi-tab merge, invalid data, blocked storage and quota failures.');
